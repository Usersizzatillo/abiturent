from django.conf import settings


class SecurityHeadersMiddleware:
    """Emit baseline security headers on every response.

    Presented as a single middleware so headers stay consistent across the
    whole API. A restrictive Content-Security-Policy is only applied outside
    DEBUG because the Django admin relies on inline scripts.
    """

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        response = self.get_response(request)

        response.setdefault("Referrer-Policy", "strict-origin-when-cross-origin")
        response.setdefault(
            "Permissions-Policy",
            "camera=(), microphone=(), geolocation=(), browsing-topics=()",
        )
        if not settings.DEBUG:
            response.setdefault(
                "Content-Security-Policy",
                "default-src 'self'; "
                "script-src 'self' 'unsafe-inline'; "
                "style-src 'self' 'unsafe-inline'; "
                "img-src 'self' data: blob:; "
                "font-src 'self' data:; "
                "connect-src 'self'; "
                "object-src 'none'; "
                "base-uri 'self'; "
                "form-action 'self'; "
                "frame-ancestors 'none'; "
                "upgrade-insecure-requests",
            )
        return response